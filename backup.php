// 1. Handle SQL Backup Download
if (isset($_GET['action']) && $_GET['action'] === 'download') {
    try {
        $dbName = 'beantrack';
        $out = "-- ========================================================\n";
        $out .= "-- BEANTRACK Database Backup (Process 7.0)\n";
        $out .= "-- Database: " . $dbName . "\n";
        $out .= "-- Server OS: " . PHP_OS . "\n";
        $out .= "-- Generated by: " . ($_SESSION['user']['name'] ?? 'Administrator') . "\n";
        $out .= "-- Date Generated: " . date('Y-m-d H:i:s') . "\n";
        $out .= "-- ========================================================\n\n";
        $out .= "SET FOREIGN_KEY_CHECKS=0;\n";
        $out .= "SET SQL_MODE = \"NO_AUTO_VALUE_ON_ZERO\";\n";
        $out .= "SET time_zone = \"+08:00\";\n";
        $out .= "SET NAMES utf8mb4;\n\n";

        $pdo->exec("SET time_zone = '+08:00'");
        $tables = $pdo->query("SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'")->fetchAll(PDO::FETCH_COLUMN);

        foreach ($tables as $table) {
            $out .= "-- --------------------------------------------------------\n";
            $out .= "-- Table structure for `$table`\n";
            $out .= "-- --------------------------------------------------------\n";
            $out .= "DROP TABLE IF EXISTS `$table`;\n";

            $createRow = $pdo->query("SHOW CREATE TABLE `$table`")->fetch(PDO::FETCH_NUM);
            $out .= $createRow[1] . ";\n\n";

            $rows = $pdo->query("SELECT * FROM `$table`")->fetchAll(PDO::FETCH_ASSOC);
            if (!empty($rows)) {
                $out .= "-- Dumping data for `$table` (" . count($rows) . " rows)\n";
                $columns = array_keys($rows[0]);
                $colList = implode('`, `', $columns);

                $chunks = array_chunk($rows, 50);
                foreach ($chunks as $chunk) {
                    $out .= "INSERT INTO `$table` (`$colList`) VALUES\n";
                    $valRows = [];
                    foreach ($chunk as $row) {
                        $vals = [];
                        foreach ($row as $v) {
                            if ($v === null) {
                                $vals[] = 'NULL';
                            } else {
                                $vals[] = $pdo->quote($v);
                            }
                        }
                        $valRows[] = "(" . implode(', ', $vals) . ")";
                    }
                    $out .= implode(",\n", $valRows) . ";\n";
                }
                $out .= "\n";
            }
        }

        $out .= "SET FOREIGN_KEY_CHECKS=1;\n";
        $out .= "-- ========================================================\n";
        $out .= "-- Backup completed successfully: " . count($tables) . " tables\n";
        $out .= "-- ========================================================\n";

        $filename = "beantrack_backup_" . date('Y-m-d_His') . ".sql";
        audit('Backup Database', 'system', null, "Exported full database backup: $filename (" . strlen($out) . " bytes)");

        header('Content-Type: application/sql; charset=utf-8');
        header('Content-Disposition: attachment; filename="' . $filename . '"');
        header('Content-Length: ' . strlen($out));
        echo $out;
        exit;
    } catch (Throwable $t) {
        $_SESSION['backup_error'] = "Backup generation failed: " . $t->getMessage();
        header('Location: backup.php');
        exit;
    }
}

// 2. Handle SQL Database Restore
if (($_SERVER['REQUEST_METHOD'] ?? '') === 'POST' && isset($_POST['action']) && $_POST['action'] === 'restore') {
    try {
        if (!isset($_POST['confirm_restore']) || $_POST['confirm_restore'] !== '1') {
            throw new Exception("Please check the confirmation box to authorize database restoration.");
        }

        if (!isset($_FILES['backup_file']) || $_FILES['backup_file']['error'] !== UPLOAD_ERR_OK) {
            $errCode = $_FILES['backup_file']['error'] ?? 'missing';
            throw new Exception("Please choose a valid SQL file to upload (Upload code: $errCode).");
        }

        $uploadedName = $_FILES['backup_file']['name'];
        $ext = strtolower(pathinfo($uploadedName, PATHINFO_EXTENSION));
        if ($ext !== 'sql') {
            throw new Exception("Invalid file type (.$ext). Only .sql database backup files are accepted.");
        }

        $sqlContent = file_get_contents($_FILES['backup_file']['tmp_name']);
        if ($sqlContent === false || trim($sqlContent) === '') {
            throw new Exception("The uploaded file is empty or could not be read.");
        }

        // Execute SQL script
        $pdo->exec("SET FOREIGN_KEY_CHECKS=0;");
        $pdo->exec("SET time_zone = '+08:00';");
        $pdo->exec($sqlContent);
        $pdo->exec("SET time_zone = '+08:00';");
        $pdo->exec("SET FOREIGN_KEY_CHECKS=1;");

        audit('Restore Database', 'system', null, "Restored database from file: $uploadedName (" . strlen($sqlContent) . " bytes)");
        $_SESSION['backup_message'] = "Database successfully restored from '$uploadedName'!";
        header('Location: backup.php');
        exit;
    } catch (Throwable $t) {
        $_SESSION['backup_error'] = "Restoration failed: " . $t->getMessage();
        header('Location: backup.php');
        exit;
    }
}

